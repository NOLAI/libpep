//! The API instantiated for ristretto255 with SHA-512, so that no type parameter is written.
//!
//! The rest of the library is generic over the group ([`Group`](crate::elgamal::arithmetic::Group))
//! and, wherever something is hashed, over the ciphersuite
//! ([`Ciphersuite`](crate::elgamal::arithmetic::Ciphersuite)). This module fixes both to
//! [`Ristretto255`] and [`Ristretto255Sha512`]. It holds
//!
//! - an alias for every generic type, under the name of the generic type and with the same
//!   feature gates: [`Pseudonym`] is `Pseudonym<Ristretto255>`, [`Transcryptor`] is
//!   `Transcryptor<Ristretto255Sha512>`, and so on. Associated functions work through the
//!   alias, so `Pseudonym::random(rng)` and `Transcryptor::new(..)` need no annotation;
//! - wrappers, with the same names, for the free functions that cannot infer the group or the
//!   ciphersuite from their arguments, like [`make_global_keys`] and [`make_session_keys`];
//! - the generic items that need no instantiation, like [`encrypt`], [`decrypt`] and
//!   [`transcrypt`], re-exported as they are.
//!
//! The [prelude](crate::prelude) re-exports the commonly needed part of it.
//!
//! Two kinds of calls cannot be hidden this way and still name the ciphersuite: the associated
//! functions that take it as a type parameter, such as `verifiable_pseudonymize::<C>` or
//! `proof.verify::<C>(..)` (write `Ristretto255Sha512` there), and the info constructors, which
//! are available as the functions [`pseudonymization_info`], [`pseudonym_rekey_info`],
//! [`attribute_rekey_info`] and [`transcryption_info`] (or as methods of [`Transcryptor`]).
//!
//! The generic items stay at their own paths, for example
//! [`data::simple::Pseudonym`](crate::data::simple::Pseudonym), for code that is generic over
//! the group or that uses another one.
//!
//! The module is generated by a macro that is private to this crate, because the feature gates
//! in its body are evaluated where it is expanded. Code that uses another group writes its own
//! aliases (or uses the generic items directly); the macro is not an extension point.
//!
//! # Examples
//!
//! A round trip: `Alice` encrypts a pseudonym, a transcryptor converts it to the domain and
//! session of `Bob`, and `Bob` decrypts it.
//!
//! ```
//! use libpep::ristretto255::*;
//!
//! let rng = &mut rand::rng();
//! let (_global_public, global_secret) = make_global_keys(rng);
//! let transcryptor = Transcryptor::new(
//!     PseudonymizationSecret::from(b"pseudonymization secret".to_vec()),
//!     EncryptionSecret::from(b"encryption secret".to_vec()),
//! );
//!
//! let (domain_a, session_a) = (PseudonymizationDomain::from("hospital"), EncryptionContext::from("session-a"));
//! let (domain_b, session_b) = (PseudonymizationDomain::from("research"), EncryptionContext::from("session-b"));
//! let keys_a = make_session_keys(&global_secret, &session_a, transcryptor.rekeying_secret());
//! let keys_b = make_session_keys(&global_secret, &session_b, transcryptor.rekeying_secret());
//!
//! let pseudonym = Pseudonym::random(rng);
//! let encrypted = encrypt(&pseudonym, &keys_a.public(), rng);
//!
//! let info = transcryptor.transcryption_info(&domain_a, &domain_b, &session_a, &session_b);
//! # #[cfg(not(feature = "elgamal3"))]
//! let transcrypted = transcrypt(&encrypted, &info, &keys_a.public(), rng);
//! # #[cfg(feature = "elgamal3")]
//! # let transcrypted = transcrypt(&encrypted, &info, rng);
//!
//! # #[cfg(not(feature = "elgamal3"))]
//! let pseudonym_b = decrypt(&transcrypted, &keys_b);
//! # #[cfg(feature = "elgamal3")]
//! # let pseudonym_b = decrypt(&transcrypted, &keys_b).unwrap();
//! assert_ne!(pseudonym, pseudonym_b);
//! ```

