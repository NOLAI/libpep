#!/usr/bin/env python3
"""Generate PEP 561 type stubs for the libpep Python module by introspection.

Run against a built module (``maturin develop`` first). Emits the ``libpep-stubs``
stub package next to this script, which maturin includes in the wheel. The submodules
are discovered by walking the module tree, so a module the build registers is stubbed
without listing it here. Parameter names come from the PyO3-generated text signatures;
parameter and return annotations are left open since the native module does not
carry them.

Usage: python bindings/python/generate_stubs.py [--check]

With ``--check``, exits non-zero if the stubs on disk differ from what would be
generated (used in CI to keep stubs in sync with the API).
"""

import ast
import inspect
import shutil
import sys
from pathlib import Path

import libpep

OUT = Path(__file__).resolve().parent / "libpep-stubs"


def discover(mod, path: str = "") -> dict[str, object]:
    """The module tree below ``mod``, keyed by dotted path relative to the package
    (``""`` for the package itself). The native modules carry short ``__name__``s, so
    the tree is walked through the attributes the build attached."""
    modules = {path: mod}
    for name in sorted(dir(mod)):
        child = getattr(mod, name)
        if not inspect.ismodule(child) or name.startswith("_") or name == "libpep":
            continue
        modules.update(discover(child, f"{path}.{name}" if path else name))
    return modules


def submodules_of(path: str, modules: dict[str, object]) -> set[str]:
    prefix = f"{path}." if path else ""
    return {
        other[len(prefix) :].split(".")[0]
        for other in modules
        if other != path and other.startswith(prefix)
    }


def signature_of(obj, is_method: bool) -> str:
    text = getattr(obj, "__text_signature__", None)
    if text:
        params = text.strip("()")
        parts = [p.strip() for p in params.split(",") if p.strip() and p.strip() != "/"]
        parts = ["self" if p == "$self" else p for p in parts]
    else:
        parts = ["*args", "**kwargs"]
    if is_method and (not parts or parts[0] != "self"):
        parts = ["self"] + parts
    return "(" + ", ".join(parts) + ")"


def first_doc_line(obj) -> str | None:
    doc = inspect.getdoc(obj)
    if not doc:
        return None
    return doc.split("\n")[0].strip()


def stub_class(name: str, cls: type) -> list[str]:
    lines = [f"class {name}:"]
    doc = first_doc_line(cls)
    if doc:
        lines.append(f'    """{doc}"""')
    members = []
    # Members inherited from a built-in base (BaseException for the error types,
    # object for everything else) are not part of this library's API, and their
    # signatures differ between Python versions, which would make the generated
    # stubs depend on the interpreter that ran this script. Only emit what the
    # extension module itself defines.
    inherited = set()
    for base in cls.__mro__[1:]:
        if base.__module__ in ("builtins", "__builtin__"):
            inherited.update(vars(base))
    for mname in sorted(dir(cls)):
        if mname.startswith("_") and mname not in ("__init__", "__eq__", "__len__"):
            continue
        if (
            mname in inherited
            and mname not in vars(cls)
            and mname not in ("__init__", "__eq__", "__len__")
        ):
            continue
        member = inspect.getattr_static(cls, mname)
        obj = getattr(cls, mname)
        if isinstance(member, staticmethod) or (
            callable(obj) and getattr(obj, "__self__", None) is cls
        ):
            members.append(f"    @staticmethod")
            members.append(f"    def {mname}{signature_of(obj, False)}: ...")
        elif isinstance(member, property) or type(member).__name__ == "getset_descriptor":
            members.append(f"    @property")
            members.append(f"    def {mname}(self): ...")
        elif callable(obj):
            if mname == "__init__":
                ctor = getattr(cls, "__text_signature__", None)
                if ctor:
                    params = [p.strip() for p in ctor.strip("()").split(",") if p.strip()]
                    members.append(
                        "    def __init__(" + ", ".join(["self"] + params) + "): ..."
                    )
                else:
                    members.append("    def __init__(self, *args, **kwargs): ...")
            else:
                members.append(f"    def {mname}{signature_of(obj, True)}: ...")
    if not members:
        members = ["    ..."]
    return lines + members


def stub_module(mod, submodule_names: set[str]) -> str:
    out = ["# Auto-generated by generate_stubs.py — do not edit by hand.", ""]
    names = [n for n in dir(mod) if not n.startswith("_")]
    for n in sorted(submodule_names & set(names)):
        out.append(f"from . import {n} as {n}")
    if submodule_names & set(names):
        out.append("")
    for n in sorted(names):
        if n in submodule_names:
            continue
        obj = getattr(mod, n)
        if inspect.ismodule(obj):
            continue
        if isinstance(obj, type):
            out.extend(stub_class(n, obj))
            out.append("")
        elif callable(obj):
            doc = first_doc_line(obj)
            out.append(f"def {n}{signature_of(obj, False)}:")
            if doc:
                out.append(f'    """{doc}"""')
            out.append("    ...")
            out.append("")
        else:
            out.append(f"{n}: object")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def stubs() -> dict[str, str]:
    """The stub files, keyed by path relative to the stub package."""
    modules = discover(libpep)
    out = {}
    for path, mod in modules.items():
        submodules = submodules_of(path, modules)
        parts = path.split(".") if path else []
        rel = "/".join(parts + ["__init__"] if submodules or not path else parts) + ".pyi"
        out[rel] = stub_module(mod, submodules)
        # A name the module exposes that is not a Python identifier (a keyword, say) makes
        # the stub unparsable and the member unreachable from Python; catch it here.
        ast.parse(out[rel], rel)
    return out


def generate(target: Path) -> None:
    files = stubs()
    if target.exists():
        shutil.rmtree(target)
    for rel, text in files.items():
        p = target / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


def main() -> int:
    if "--check" in sys.argv:
        current = {str(p.relative_to(OUT)): p.read_text() for p in OUT.rglob("*.pyi")}
        new = stubs()
        if current != new:
            changed = sorted(
                set(current) ^ set(new)
                | {k for k in set(current) & set(new) if current[k] != new[k]}
            )
            print("stubs out of date:", ", ".join(changed))
            print("run: python bindings/python/generate_stubs.py")
            return 1
        print("stubs up to date")
        return 0
    generate(OUT)
    print(f"stubs written to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
